import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const source=fs.readFileSync(path.join(here,'../materials/liam-learning-app/science-geography-teaching-v4.js'),'utf8');
const S={subject:'biology',view:'home',data:{biology:{chapters:[]},geography:{chapters:[]}}};
const TERM_DEFS={biology:{population:['All members of one species living in one area.','Example.']},geography:{}};
const sandbox={console,S,TERM_DEFS,guideFor:(ch)=>({title:ch.title||'Generated',big:'Generated',mastery:[],steps:[{t:'Later block',k:'population',learn:'A population can change when food becomes scarce. Limited food can reduce survival and reproduction. Competition can become stronger as the population becomes crowded. This changes population size over time.',try:'Unrelated question about a word not taught here.',apply:'',more:''},{t:'Chapter mastery check',questions:['Explain the chapter.'],learn:'Mastery'}]}),render:()=>{}};
vm.createContext(sandbox);vm.runInContext(source,sandbox,{filename:'science-geography-teaching-v4.js'});
const bio=sandbox.__BIO4_TEACHING_V4();
assert.ok(bio.steps.length>=7);
assert.match(bio.steps[0].learn,/J-shaped/);
assert.match(bio.steps[1].learn,/carrying capacity/i);
assert.match(bio.steps[3].learn,/density-dependent/i);
const bv=bio.steps.find(s=>s.vocabularyCheck);
assert.ok(bv.sort.items.length>=8);
assert.ok(bv.sort.items.every(i=>!/Liam should|chapter term|specific living system/i.test(i.label)));
const geo=sandbox.__GEO4_TEACHING_V4();
assert.ok(geo.steps.length>=6);
assert.match(geo.steps[0].learn,/death rate/i);
assert.match(geo.steps[0].learn,/natural increase/i);
assert.match(geo.steps[2].learn,/population density/i);
assert.match(geo.steps[3].learn,/migration/i);
const gv=geo.steps.find(s=>s.vocabularyCheck);
assert.ok(gv.sort.items.length>=8);
assert.ok(gv.sort.items.every(i=>!/Liam should|chapter term|use this concept/i.test(i.label)));
sandbox.S.subject='geography';
const later=sandbox.guideFor({number:5,title:'Later Geography',sections:[]});
assert.match(later.steps[0].try,/Using only the lesson above/i);
assert.doesNotMatch(later.steps[0].try,/word not taught/i);
sandbox.S.subject='biology';
const laterBio=sandbox.guideFor({number:5,title:'Later Biology',sections:[]});
assert.match(laterBio.steps[0].try,/Using only the lesson above/i);
const audit=sandbox.__auditScienceGeographyTeachingV4();
assert.equal(audit.passed,true);
console.log('PASS: Chapter 4 is taught explicitly and later science/geography questions are block-aligned');
